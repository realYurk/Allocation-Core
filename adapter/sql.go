package adapter

import (
	"context"
	"database/sql"
	"fmt"
	"io"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"
)

// SQLSource uses a caller-supplied, ALREADY OPEN, read-only-capable database/sql
// handle. It does not register drivers or store database credentials. It never
// accepts SQL expressions from input: SELECT and WHERE are generated here.
// A read-only DB user is still required: driver enforcement varies.
type SQLSource struct {
	DB          *sql.DB
	Table       string // `table` or `schema.table`, restricted identifiers
	ColumnsList []string
	Equal       map[string]string
	// KeyColumn must name a UNIQUE, NOT NULL signed BIGINT column when batching.
	// A non-unique or non-monotonic key fails closed; never use OFFSET paging.
	KeyColumn string
	BatchSize int
	Tx        *sql.Tx // optional external snapshot transaction (owned by the caller)
}

var identifier = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

func sqlIdent(v string) (string, error) {
	parts := strings.Split(v, ".")
	if len(parts) < 1 || len(parts) > 2 {
		return "", fmt.Errorf("invalid table identifier %q", v)
	}
	for _, p := range parts {
		if !identifier.MatchString(p) {
			return "", fmt.Errorf("invalid SQL identifier %q", p)
		}
	}
	quoted := make([]string, len(parts))
	for i, p := range parts {
		quoted[i] = "`" + p + "`"
	}
	return strings.Join(quoted, "."), nil
}
func (s SQLSource) Statement() (string, []any, error) {
	if len(s.ColumnsList) == 0 {
		return "", nil, fmt.Errorf("columns required")
	}
	table, e := sqlIdent(s.Table)
	if e != nil {
		return "", nil, e
	}
	cols := make([]string, len(s.ColumnsList))
	seen := map[string]bool{}
	for i, c := range s.ColumnsList {
		if seen[c] {
			return "", nil, fmt.Errorf("duplicate column %q", c)
		}
		seen[c] = true
		cols[i], e = sqlIdent(c)
		if e != nil || strings.Contains(c, ".") {
			return "", nil, fmt.Errorf("invalid column %q", c)
		}
	}
	q := "SELECT " + strings.Join(cols, ", ") + " FROM " + table
	keys := make([]string, 0, len(s.Equal))
	for k := range s.Equal {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	args := make([]any, 0, len(keys))
	clauses := make([]string, 0, len(keys))
	for _, k := range keys {
		if !seen[k] {
			return "", nil, fmt.Errorf("filter column %q must be selected", k)
		}
		c, _ := sqlIdent(k)
		clauses = append(clauses, c+" = ?")
		args = append(args, s.Equal[k])
	}
	if len(clauses) > 0 {
		q += " WHERE " + strings.Join(clauses, " AND ")
	}
	return q, args, nil
}
func (s SQLSource) Open(ctx context.Context) (Rows, error) {
	if s.DB == nil && s.Tx == nil {
		return nil, fmt.Errorf("nil SQL handle")
	}
	stmt, args, e := s.Statement()
	if e != nil {
		return nil, e
	}
	if s.BatchSize < 0 || s.BatchSize > 100000 {
		return nil, fmt.Errorf("batch_size must be 0..100000")
	}
	if s.BatchSize > 0 {
		if s.KeyColumn == "" {
			return nil, fmt.Errorf("key_column required for keyset batching")
		}
		found := false
		for _, c := range s.ColumnsList {
			if c == s.KeyColumn {
				found = true
			}
		}
		if !found {
			return nil, fmt.Errorf("key_column must be selected")
		}
		if _, e = sqlIdent(s.KeyColumn); e != nil || strings.Contains(s.KeyColumn, ".") {
			return nil, fmt.Errorf("invalid key_column")
		}
	}
	tx := s.Tx
	owned := false
	if tx == nil {
		tx, e = s.DB.BeginTx(ctx, &sql.TxOptions{ReadOnly: true, Isolation: sql.LevelRepeatableRead})
		if e != nil {
			return nil, fmt.Errorf("REPEATABLE READ read-only transaction rejected: %w", e)
		}
		owned = true
	}
	qr := &sqlRows{tx: tx, owned: owned, cols: append([]string(nil), s.ColumnsList...), stmt: stmt, args: args, key: s.KeyColumn, batch: s.BatchSize, ctx: ctx}
	if s.BatchSize == 0 {
		qr.rows, e = tx.QueryContext(ctx, stmt, args...)
	} else {
		e = qr.queryBatch(false)
	}
	if e != nil {
		if owned {
			_ = tx.Rollback()
		}
		return nil, e
	}
	return qr, nil
}

type sqlRows struct {
	rows    *sql.Rows
	tx      *sql.Tx
	owned   bool
	cols    []string
	stmt    string
	args    []any
	key     string
	batch   int
	ctx     context.Context
	fetched int
	lastKey int64
	hasLast bool
	done    bool
	closed  bool
}

func (r *sqlRows) queryBatch(after bool) error {
	stmt := r.stmt
	args := append([]any(nil), r.args...)
	// Statement generated by SQLSource.Statement contains only whitelisted
	// identifiers and parameterized equality predicates. Append keyset paging.
	if after {
		if strings.Contains(stmt, " WHERE ") {
			stmt += " AND "
		} else {
			stmt += " WHERE "
		}
		stmt += "`" + r.key + "` > ?"
		args = append(args, r.lastKey)
	}
	stmt += " ORDER BY `" + r.key + "` ASC LIMIT ?"
	args = append(args, r.batch)
	rows, e := r.tx.QueryContext(r.ctx, stmt, args...)
	if e != nil {
		return fmt.Errorf("keyset query failed: %w", e)
	}
	r.rows = rows
	r.fetched = 0
	return nil
}

func (r *sqlRows) Columns() []string { return append([]string(nil), r.cols...) }
func (r *sqlRows) Next() ([]string, error) {
	if r.closed {
		return nil, fmt.Errorf("SQL cursor already closed")
	}
	for {
		if e := r.ctx.Err(); e != nil {
			return nil, e
		}
		if r.rows.Next() {
			break
		}
		if e := r.rows.Err(); e != nil {
			return nil, e
		}
		if r.batch == 0 || r.fetched < r.batch || r.done {
			return nil, io.EOF
		}
		if e := r.rows.Close(); e != nil {
			return nil, e
		}
		if e := r.queryBatch(true); e != nil {
			return nil, e
		}
		// If prior batch had exactly batch_size rows, query the next page.
		// An empty page terminates normally.
	}
	values := make([]any, len(r.cols))
	dest := make([]any, len(r.cols))
	for i := range values {
		dest[i] = &values[i]
	}
	if e := r.rows.Scan(dest...); e != nil {
		return nil, e
	}
	result := make([]string, len(values))
	for i, v := range values {
		switch v := v.(type) {
		case nil:
			return nil, fmt.Errorf("SQL NULL in selected field %q", r.cols[i])
		case string:
			result[i] = v
		case []byte:
			result[i] = string(v)
		case int64:
			result[i] = strconv.FormatInt(v, 10)
		case bool:
			result[i] = strconv.FormatBool(v)
		case time.Time:
			result[i] = v.Format("2006-01-02 15:04:05.999999999")
		case float64:
			return nil, fmt.Errorf("SQL FLOAT in %q cannot guarantee exact decimals", r.cols[i])
		default:
			return nil, fmt.Errorf("unsupported SQL type %T in %q", v, r.cols[i])
		}
	}
	if r.batch > 0 {
		kIdx := -1
		for i, c := range r.cols {
			if c == r.key {
				kIdx = i
				break
			}
		}
		k, e := strconv.ParseInt(result[kIdx], 10, 64)
		if e != nil {
			return nil, fmt.Errorf("key_column %s must be signed BIGINT: %w", r.key, e)
		}
		if r.hasLast && k <= r.lastKey {
			return nil, fmt.Errorf("key_column %s not strictly increasing: %d after %d; ensure UNIQUE NOT NULL key and stable ordering", r.key, k, r.lastKey)
		}
		r.hasLast = true
		r.lastKey = k
		r.fetched++
	}
	return result, nil
}
func (r *sqlRows) Close() error {
	if r.closed {
		return nil
	}
	r.closed = true
	e := r.rows.Close()
	if r.owned {
		rollback := r.tx.Rollback()
		if e == nil && rollback != nil && rollback != sql.ErrTxDone {
			e = rollback
		}
	}
	return e
}
